#!/usr/bin/env python3
"""Audit: which sub-topics still use the Basic / Intermediate / Competent tiers, and what each needs to move to the
one-pool milestone framework (ADR 0011: a sub-topic switches to one past-paper pool, playable at 20 past-paper questions;
generated questions are support only and never count toward milestones).

Reads the site's own build inputs (rewards.json order, pp_counts.json, PP_SWITCH in pastpaper.ts, OWNER_MERGE in
train.ts) and the built banks (site/dist/data/quiz/*.json: run `npm run build` in site/ first). Writes
docs/audit/milestone-migration.md and prints the summary. Exit 0 always (an audit, not a gate).
"""
import glob
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / 'site'
MIN_POOL = 20  # store.ts MIN_POOL / pastpaper.ts PP_MIN_TIER
SCHOOL = {'math': 'Math', 'science': 'Science', 'english': 'English', 'chinese': 'Chinese'}


def main():
    order = json.loads((SITE / 'src/data/rewards.json').read_text())['order']
    pp = json.loads((SITE / 'src/data/pp_counts.json').read_text())
    pp_src = (SITE / 'src/lib/pastpaper.ts').read_text()
    enabled = re.search(r'export const PP_ENABLED = (true|false)', pp_src).group(1) == 'true'
    switch = dict(re.findall(r"'([a-z0-9-]+)':\s*'(pool|merge|replace)'", pp_src))
    owner_merge = set(re.findall(r"'([a-z0-9-]+)'", re.search(r'OWNER_MERGE = new Set\(\[([^\]]*)\]', (SITE / 'src/lib/train.ts').read_text()).group(1)))
    gen = defaultdict(Counter)
    banks = glob.glob(str(SITE / 'dist/data/quiz/*.json'))
    if not banks:
        raise SystemExit('no built banks: run `npm run build` in site/ first')
    for f in banks:
        b = json.loads(Path(f).read_text())
        for q in (b['questions'] if isinstance(b, dict) else b):
            gen[q['sub']][q['level']] += 1

    rows = []
    for school, subs in order.items():
        for s in subs:
            sid = s['id']
            p = sum(pp.get(f'{sid}|{t}', 0) for t in 'bic')
            g = gen.get(sid, Counter())
            gt = sum(g.values())
            mode = switch.get(sid) if enabled else None
            if mode == 'pool':
                cat = 'milestones'
            elif sid in owner_merge:
                cat = 'owner-kept-tiers'
            elif p >= MIN_POOL:
                cat = 'switch-now'
            elif p > 0:
                cat = 'needs-pp'
            elif gt:
                cat = 'generated-only'
            else:
                cat = 'no-questions'
            rows.append(dict(school=school, id=sid, name=s['name'], topic=s.get('topicName', ''), pp=p, gen=gt,
                             b=g.get('basic', 0), i=g.get('intermediate', 0), c=g.get('competent', 0), mode=mode or '-', cat=cat))

    cats = ['milestones', 'switch-now', 'owner-kept-tiers', 'needs-pp', 'generated-only', 'no-questions']
    what = {
        'milestones': 'Already on milestones (one past-paper pool).',
        'switch-now': f'{MIN_POOL}+ past-paper questions but still on tiers: switch to `pool` in PP_SWITCH (no new content needed).',
        'owner-kept-tiers': 'Owner kept tiers on purpose (OWNER_MERGE, ADR 0011 amendment).',
        'needs-pp': f'Some past-paper questions, fewer than {MIN_POOL}: tiers with them merged in; needs more past-paper questions (or an owner decision to pool generated questions).',
        'generated-only': 'Generated questions only, no past-paper questions: stays on tiers until past-paper questions are imported, or the owner allows a generated pool.',
        'no-questions': 'No questions yet ("Coming soon"): nothing to migrate.',
    }
    out = ['# Milestone migration audit', '',
           'Generated by `scripts/quiz/audit_milestones.py` (re-run after banks or past-paper uploads change). Rule (ADR 0011): '
           f'a sub-topic moves to one past-paper pool with milestones at {MIN_POOL}+ past-paper questions; generated questions never count.', '']
    out += ['## Summary', '', '| Subject | ' + ' | '.join(cats) + ' | Total |', '|---|' + '---:|' * (len(cats) + 1)]
    for school in order:
        c = Counter(r['cat'] for r in rows if r['school'] == school)
        out.append(f"| {SCHOOL[school]} | " + ' | '.join(str(c[k]) for k in cats) + f" | {sum(c.values())} |")
    c = Counter(r['cat'] for r in rows)
    out.append('| **All** | ' + ' | '.join(f'**{c[k]}**' for k in cats) + f' | **{len(rows)}** |')
    for k in cats[1:]:
        rs = [r for r in rows if r['cat'] == k]
        out += ['', f'## {k} ({len(rs)})', '', what[k], '']
        if not rs:
            continue
        out += ['| Subject | Sub-topic | Topic | Past-paper | Generated (B / I / C) | Switch |', '|---|---|---|---:|---|---|']
        for r in sorted(rs, key=lambda r: (list(order).index(r['school']), -r['pp'], r['name'])):
            out.append(f"| {SCHOOL[r['school']]} | {r['name']} (`{r['id']}`) | {r['topic']} | {r['pp']} | {r['gen']} ({r['b']} / {r['i']} / {r['c']}) | {r['mode']} |")
    dest = ROOT / 'docs/audit/milestone-migration.md'
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text('\n'.join(out) + '\n')
    print('\n'.join(out[4:4 + len(order) + 3]))
    print(f'-> {dest.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
